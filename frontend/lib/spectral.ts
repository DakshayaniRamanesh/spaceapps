export function spectralChannels(detector: Detector) {
  return CHANNEL_WINDOWS[detector].map(([center_um, min, max], index) => ({
    channel: index + 1,
    center_um,
    min_wavelength_um: min,
    max_wavelength_um: max,
  }));
}

export function spectralSubBands(detector: Detector) {
  const channels = spectralChannels(detector);
  return [
    { label: "Short λ", first: 0, last: 5 },
    { label: "Middle λ", first: 6, last: 11 },
    { label: "Long λ", first: 12, last: 16 },
  ].map(({ label, first, last }) => ({
    label,
    min_wavelength_um: channels[first].min_wavelength_um,
    max_wavelength_um: channels[last].max_wavelength_um,
  }));
}
